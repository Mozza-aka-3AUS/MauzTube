/**
 * Anteprime della barra (storyboard YouTube): immagini "sprite" con [cols]×[rows] fotogrammi
 * da [frameWidth]×[frameHeight] px, uno ogni [durationPerFrameMs].
 */
data class Storyboard(
    val urls: List<String>,
    val frameWidth: Int,
    val frameHeight: Int,
    val totalCount: Int,
    val durationPerFrameMs: Int,
    val cols: Int,
    val rows: Int,
) {
    /** (indice sprite, x, y) del fotogramma alla posizione [positionMs]. */
    fun frameAt(positionMs: Long): Triple<Int, Int, Int> {
        val index = (positionMs / durationPerFrameMs.coerceAtLeast(1)).toInt().coerceIn(0, (totalCount - 1).coerceAtLeast(0))
        val perPage = (cols * rows).coerceAtLeast(1)
        val inPage = index % perPage
        return Triple(index / perPage, (inPage % cols) * frameWidth, (inPage / cols) * frameHeight)
    }
}

data class SubtitleOption(
    val url: String,
    val mimeType: String,
    val languageTag: String,
    val label: String,
    val autoGenerated: Boolean,
)

/** Stream estratti direttamente dai server video: nessuna pubblicità può esservi inserita. */
data class PlayableStreams(
    val videoOnly: List<StreamOption>,
    val audioOnly: List<StreamOption>,
    val muxed: List<StreamOption>,
    val hlsUrl: String?,
    val dashMpdUrl: String?,
)

data class StreamOption(
    val url: String,
    /**
     * Manifest DASH generato dai metadati itag (indexRange/initRange). Permette a ExoPlayer
     * di scaricare a blocchi con range limitati: avvio e seek molto più rapidi e nessun
     * throttling, a differenza di un'unica richiesta progressiva aperta.
     */
    val dashManifest: String?,
    val mimeType: String?,
    val codec: String?,
    val height: Int,
    val fps: Int,
    val bitrate: Int,
    val isOriginalAudio: Boolean,
    /** Dimensione in byte (stima dei download), -1 se sconosciuta. */
    val contentLength: Long = -1,
    val itag: Int = -1,
)

class ShortsBlockedException : Exception(tr("Shorts are disabled in MauzTube", "Gli Shorts sono disattivati in MauzTube"))
class NoPlayableStreamException : Exception(tr("No playable stream found", "Nessuno stream riproducibile trovato"))
