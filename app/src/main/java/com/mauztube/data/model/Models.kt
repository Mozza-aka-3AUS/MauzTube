/**
 * Una pagina di risultati. [loadNext] incapsula il cursore di paginazione di NewPipe
 * (Page + LinkHandler) senza esporlo agli strati superiori.
 */
class Paged<T>(
    val items: List<T>,
    val loadNext: (suspend () -> Paged<T>)?,
)

data class ChannelDetails(
